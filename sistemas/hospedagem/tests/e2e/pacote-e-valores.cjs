// Reserva de pacote pelo site e edição de diária com centavos no painel. Rode depois de fluxo-completo.cjs.
const { chromium } = require('playwright');
const B = process.env.APP_URL || 'http://localhost:3100';
const log = (ok, msg) => { console.log(`${ok ? 'ok' : 'FALHOU'} - ${msg}`); if (!ok) process.exitCode = 1; };
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
  await ctx.route(/unsplash|fonts\.g/, (r) => r.abort());
  const g = await ctx.newPage();
  await g.goto(B + '/', { waitUntil: 'networkidle' });
  await g.click('.package:has-text("Virada pé na areia") button:has-text("Reservar")');
  await g.waitForTimeout(500);
  log((await g.textContent('.summary__house')).includes('Pacote'), 'botão do pacote preenche a reserva com o pacote');
  await g.click('button:has-text("Continuar")');
  await g.waitForSelector('.guest-form');
  const total = await g.textContent('.breakdown__total dd');
  log(/12\.900/.test(total), `valor fechado do pacote: ${total}`);
  await g.fill('input[autocomplete="name"]', 'Pedro Pacote');
  await g.fill('input[type="tel"]', '71977776666');
  await g.check('.check input');
  await g.click('button:has-text("Reservar agora")');
  await g.waitForURL(/\/reserva\//, { timeout: 15000 });
  log(await g.isVisible('text=Virada pé na areia'), 'reserva do pacote criada');

  const a = await (await b.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
  a.on('dialog', (d) => d.accept());
  await a.goto(B + '/admin/login');
  await a.fill('input[type="email"]', 'dono@ex.com');
  await a.fill('input[type="password"]', 'senha123');
  await a.click('button[type="submit"]');
  await a.waitForURL(B + '/admin');
  await a.goto(B + '/admin/casas');
  await a.click('.house-admin:has-text("Bangalô Brisa")');
  await a.waitForSelector('input[name="price"]');
  log((await a.inputValue('input[name="price"]')) === '420', `diária exibida sem ".00": ${await a.inputValue('input[name="price"]')}`);
  await a.fill('input[name="price"]', '1.290,50');
  await a.click('button:has-text("Salvar alterações")');
  await a.waitForSelector('.notice--ok');
  await a.reload();
  const shown = await a.inputValue('input[name="price"]');
  log(shown === '1290,5', `depois de salvar "1.290,50" aparece ${shown}`);
  await a.click('button:has-text("Salvar alterações")');
  await a.waitForSelector('.notice--ok');
  await a.reload();
  log((await a.inputValue('input[name="price"]')) === '1290,5', 'salvar de novo mantém 1290,5 (sem virar 12905)');
  await a.fill('input[name="price"]', '420');
  await a.click('button:has-text("Salvar alterações")');
  await a.waitForSelector('.notice--ok');
  await b.close();
})().catch((e) => { console.error('ERRO', e.message); process.exit(1); });
